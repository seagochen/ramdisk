"""The systemd user unit that recreates the ramdisk directories at every login.

The unit is rendered from code so it runs `<this interpreter> -m ramdisk login` from wherever
this checkout lives, with no hard-coded project path.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

from .core import Ctx, Fail, query, say

NAME = "ramdisk-dirs.service"
PACKAGE_DIR = Path(__file__).resolve().parent


def _systemd_escape(value: str) -> str:
    return value.replace("%", "%%")


def _exec_word(value: str) -> str:
    value = _systemd_escape(value)
    if any(c in value for c in ' \t"\\'):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


def render(python: str | None = None) -> str:
    python = python or sys.executable
    return f"""\
# Generated by `ramdisk install-unit` -- edits are overwritten.
[Unit]
Description=Recreate AI-agent scratch directories on the per-user tmpfs
# /run/user/%U is mounted by logind before the user manager starts, so no mount ordering is
# needed. Runs before the user's own services/sessions, so the agent symlinks and
# config.toml paths are never dangling when Claude Code / Codex start.
DefaultDependencies=no
Before=basic.target
# Skipped (not failed) if the package was uninstalled or the checkout moved.
ConditionPathExists={_systemd_escape(str(PACKAGE_DIR / "__main__.py"))}

[Service]
Type=oneshot
RemainAfterExit=yes
# -m imports from the working directory first, which also makes a source checkout work.
WorkingDirectory={_systemd_escape(str(PACKAGE_DIR.parent))}
ExecStart={_exec_word(python)} -m ramdisk login

[Install]
WantedBy=default.target
"""


def _systemctl_ok(*args) -> bool:
    return query("systemctl", "--user", *args, NAME)


def is_installed() -> bool:
    return _systemctl_ok("cat")


def _up_to_date(dst: Path) -> bool:
    try:
        return not dst.is_symlink() and dst.read_text() == render()
    except OSError:
        return False


def install(ctx: Ctx) -> None:
    """Write the unit as a real file and enable it; a stale or symlinked copy is replaced."""
    dst = ctx.unit_dst
    if _up_to_date(dst) and _systemctl_ok("is-enabled"):
        say("OK   login unit up to date and enabled")
        return
    if dst.is_symlink():
        ctx.remove(dst)
        say("MOVE unit was a symlink -- replacing it with a real file")
    ctx.mkdir(dst.parent)
    if ctx.dry:
        say(f"DRY  write {dst}")
    else:
        dst.write_text(render())
    say(f"NEW  login unit installed/refreshed: {dst}")
    if os.environ.get("INVOCATION_ID"):
        # Running AS that unit: no daemon-reload from inside its own job; read at next login anyway.
        say("     (running under systemd -- daemon-reload skipped, effective next login)")
    else:
        ctx.run("systemctl", "--user", "daemon-reload")
        ctx.run("systemctl", "--user", "reenable", NAME)


def uninstall(ctx: Ctx) -> None:
    dst = ctx.unit_dst
    if not (is_installed() or dst.exists() or dst.is_symlink()):
        say("OK   login unit not installed")
        return
    ctx.run("systemctl", "--user", "disable", NAME, check=False)
    ctx.remove(dst)
    ctx.run("systemctl", "--user", "daemon-reload")
    say("GONE login unit removed")


def check(ctx: Ctx) -> None:
    if not is_installed():
        say(f"FAIL {NAME} is not installed -- after the next reboot the ramdisk targets are gone")
        say("     and Claude Code / Codex cannot write their files  -> ramdisk install-unit")
        ctx.n.fail += 1
        return
    if _systemctl_ok("is-enabled"):
        say(f"OK   {NAME} is enabled")
    else:
        say(f"FAIL {NAME} is installed but not enabled  -> ramdisk install-unit")
        ctx.n.fail += 1
    if _systemctl_ok("is-failed"):
        say(f"FAIL {NAME} failed at the last login -- journalctl --user -u {NAME.removesuffix('.service')}")
        ctx.n.fail += 1
    if not _up_to_date(ctx.unit_dst):
        say("WARN installed unit is stale (other interpreter or package location)  -> ramdisk install-unit")
